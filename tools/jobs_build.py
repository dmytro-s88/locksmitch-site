"""Recent jobs as plain text in the HTML: one data file feeds the city pages, the home page, /car-key-replacement/ and llms.txt.

Add a job: put it at the top of "jobs" in tools/jobs.json (newest first): "date" as YYYY-MM, "vehicle" as year make model,
"service" in a few plain words, "city" exactly as the city page is named (leave "city" empty when it is not certain).
Then run from the site root:
    python3 -I tools/jobs_build.py
Rerun is safe: nothing changes when the data did not change.

The repo is public. Never put customer names, street addresses, phone numbers, prices or lead numbers into jobs.json.
Only real completed jobs, one plain line each, nothing added.

What it writes (always between <!-- jobs:start --> and <!-- jobs:end -->):
  - city pages with at least one job: "Recent jobs in <City>" (the CITY_MAX newest) after the local text block;
  - LIST_PAGES: a text list of the LIST_MAX newest jobs inside the "Recent jobs" section, under the Instagram photos;
    the section is no longer hidden there, so the text is visible even before (or without) the photos;
  - llms.txt: the "## Recent jobs" section (the LLMS_MAX newest).
The Spanish pages are not touched. No JSON-LD is written.
"""
import glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST_PAGES = ['index.html', 'car-key-replacement/index.html']
CITY_MAX, LIST_MAX, LLMS_MAX = 3, 8, 10
START = '<!-- jobs:start (generated by tools/jobs_build.py from tools/jobs.json) -->'
END = '<!-- jobs:end -->'
BLOCK_RE = re.compile(r'[ \t]*<!-- jobs:start.*?<!-- jobs:end -->\n', re.S)
MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']

JOBS = json.load(open(os.path.join(ROOT, 'tools', 'jobs.json'), encoding='utf-8'))['jobs']
JOBS = sorted(JOBS, key=lambda j: j['date'], reverse=True)   # stable: the file order decides inside one month


def esc(t):
    return html.escape(t, quote=False)


def when(job, short):
    y, m = job['date'].split('-')[:2]
    name = MONTHS[int(m) - 1]
    return (name[:3] if short else name) + ' ' + y


def lower(service):
    return service[0].lower() + service[1:]


def line(job):
    """2019 Ford Ranger - all keys lost - Johns Creek - Nov 2026"""
    parts = [job['vehicle'], lower(job['service'])] + ([job['city']] if job.get('city') else []) + [when(job, True)]
    return ' - '.join(parts)


def slug(city):
    return re.sub(r'[^a-z]', '', city.lower())


def name(job):
    """Vehicle name, linked to the job's own page /jobs/<slug>/ when it has one (tools/job_pages.py)."""
    if job.get('slug'):
        return '<a href="/jobs/%s/">%s</a>' % (job['slug'], esc(job['vehicle']))
    return esc(job['vehicle'])


def city_block(city, jobs):
    items = ''.join('<li><b>%s:</b> %s, %s</li>' % (name(j), esc(lower(j['service'])), when(j, False)) for j in jobs[:CITY_MAX])
    return ('        ' + START + '\n'
            '        <div class="local-jobs"><h3 class="sub">Recent jobs in %s</h3><ul class="price-list">%s</ul></div>\n'
            '        ' + END + '\n') % (esc(city), items)


def list_block():
    items = ''.join('        <li><b>%s</b> <span>%s</span></li>\n' % (name(j), esc(line(j).split(' - ', 1)[1])) for j in JOBS[:LIST_MAX])
    more = '      <p class="jobs-more"><a href="/jobs/">All recent jobs, with photos&nbsp;→</a></p>\n' if any(j.get('slug') for j in JOBS) else ''
    return ('      ' + START + '\n'
            '      <ul class="jobs-list">\n%s      </ul>\n%s'
            '      ' + END + '\n') % (items, more)


def fix_page(rel, by_city):
    path = os.path.join(ROOT, rel)
    old = open(path, encoding='utf-8').read()
    s = BLOCK_RE.sub('', old)
    if rel in LIST_PAGES:
        s = s.replace('<section id="work" hidden>', '<section id="work">', 1)
        anchor = '      <div class="gallery" id="gallery"></div>\n'
        if anchor not in s:
            raise SystemExit('no photo gallery to put the job list under in ' + rel)
        s = s.replace(anchor, anchor + list_block(), 1)
    city = re.search(r'<html[^>]* data-city="([^"]+)"', s)
    if city and html.unescape(city.group(1)) in by_city:
        name = html.unescape(city.group(1))
        m = re.search(r'<div class="local-more">.*?</div>\n', s, re.S)
        if not m:
            raise SystemExit('no local text block to put the jobs after in ' + rel)
        s = s[:m.end()] + city_block(name, by_city[name]) + s[m.end():]
    if s != old:
        open(path, 'w', encoding='utf-8').write(s)
    return s != old


def fix_llms():
    path = os.path.join(ROOT, 'llms.txt')
    old = open(path, encoding='utf-8').read()
    s = re.sub(r'## Recent jobs\n.*?(?=## )', '', old, flags=re.S)
    section = ('## Recent jobs\nReal jobs completed by LocksMitch, newest first (vehicle, service, city, month):\n' +
               ''.join('- ' + line(j) + (' (https://locksmitch.com/jobs/%s/)' % j['slug'] if j.get('slug') else '') + '\n' for j in JOBS[:LLMS_MAX]) +
               ('All recent jobs with photos: https://locksmitch.com/jobs/\n' if any(j.get('slug') for j in JOBS) else '') + '\n')
    anchor = '## Service area\n'
    if anchor not in s:
        raise SystemExit('llms.txt: no "Service area" section')
    s = s.replace(anchor, section + anchor, 1)
    if s != old:
        open(path, 'w', encoding='utf-8').write(s)
    return s != old


def main():
    by_city = {}
    for j in JOBS:
        if j.get('city'):
            by_city.setdefault(j['city'], []).append(j)
    pages = sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, '**', '*.html'), recursive=True))
    pages = [p for p in pages if not p.startswith('es' + os.sep)]
    have = {html.unescape(m.group(1)) for p in pages for m in [re.search(r'<html[^>]* data-city="([^"]+)"', open(os.path.join(ROOT, p), encoding='utf-8').read(2000))] if m}
    for c in sorted(set(by_city) - have):
        print('no city page for "%s": its jobs go only into the general lists' % c)
    changed = [p for p in pages if fix_page(p, by_city)]
    llms = fix_llms()
    print('jobs: %d; cities with a block: %s; pages changed: %d%s' % (
        len(JOBS), ', '.join('%s (%d)' % (c, len(by_city[c])) for c in sorted(by_city) if c in have), len(changed), ', llms.txt changed' if llms else ''))


main()
