def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def typo(t):
    t = re.sub(r'"([^"]*)"', '“\\1”', t)
    return t.replace("'", '’')


def block(head, items):
    li = []
    for lead, text, job in items:
        for t in (lead, text):
            if '—' in t or '–' in t:
                raise SystemExit('long dash in: ' + t)
        if job and not os.path.isfile(os.path.join(ROOT, 'jobs', job, 'index.html')):
            raise SystemExit('no job page: ' + job)
        link = ' <a href="/jobs/%s/">Read the job&nbsp;→</a>' % job if job else ''
        li.append('<li><b>%s</b> %s%s</li>' % (esc(typo(lead)), esc(typo(text)), link))
    return ('        ' + START + '\n'
            '        <div class="local-notes"><h3 class="sub">' + esc(head) + '</h3><ul class="price-list">' + ''.join(li) + '</ul></div>\n'
            '        ' + END + '\n')


def main():
    for slug, (head, items) in NOTES.items():
        p = os.path.join(ROOT, slug + '-key-replacement', 'index.html')
        old = open(p, encoding='utf-8').read()
        s = re.sub(r'[ \t]*' + re.escape(START) + r'.*?' + re.escape(END) + r'\n', '', old, flags=re.S)
        m = re.search(r'<!-- jobs:end -->\n', s) or re.search(r'<div class="local-more">.*?</div>\n', s, re.S)
        if not m:
            raise SystemExit('nowhere to put the notes in ' + slug)
        s = s[:m.end()] + block(head, items) + s[m.end():]
        if s != old:
            open(p, 'w', encoding='utf-8').write(s)
        print(slug, 'ok,', sum(len((a + ' ' + b).split()) for a, b, _ in items), 'words', '(changed)' if s != old else '')


main()
