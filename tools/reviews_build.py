"""Google reviews on the site: one data file feeds the visible block, the JSON-LD and llms.txt.

Add a review: copy it word for word into tools/reviews.json (full name as shown on Google, with normal capitals: decision of Dima 2026-11-18, the reviews are public; rating, date,
text), set "checked" to the day you read the profile, then run from the site root:
    python3 -I tools/reviews_build.py
Rerun is safe: nothing changes when the data did not change. Only real reviews, never reworded.

What it writes:
  - the block between <!-- reviews:start --> and <!-- reviews:end --> on PAGES (first run: after the hidden "Recent jobs" section);
  - NO review markup: "aggregateRating" and "review" are stripped from the Locksmith JSON-LD everywhere (REVIEW_MARKUP = False).
    Google does not allow marking up ratings taken from another site (ours come from Google itself), it gives no stars,
    and a flagged site can lose its other rich results. The visible block stays. Decision of Dima, 2026-11-18;
  - the Google profile link in "sameAs" on every page that has sameAs;
  - the "Google" lines in llms.txt;
  - the first-screen trust line under the hero buttons, between <!-- trust:start --> and <!-- trust:end -->, on the home
    page, the city, county and Lake Lanier pages and the five service pages: "5.0 on Google" (rating from reviews.json,
    link to the Google profile) and two starting prices from /pricing/ for that page's travel zone (TRUST_* below).
The Spanish pages are not touched here: tools/es_build.py translates the trust line of the home page.
"""
import datetime, glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REVIEW_MARKUP = False   # see the docstring: reviews copied from Google must not be marked up as our own
PAGES = ['index.html', 'cumming/index.html', 'car-key-replacement/index.html']
START = '<!-- reviews:start (generated by tools/reviews_build.py from tools/reviews.json) -->'
END = '<!-- reviews:end -->'
BLOCK_RE = re.compile(r'  <!-- reviews:start.*?<!-- reviews:end -->\n\n', re.S)
AFTER_RE = re.compile(r'  <section id="work"[^>]*>.*?</section>\n\n', re.S)   # hidden or not (tools/jobs_build.py shows it on some pages)

# Trust line. Prices are the ones on /pricing/: lockout $75 in Cumming, Forsyth County and Sugar Hill, $100 up to 25 miles,
# $125 up to 40 miles; chip key from $140, key jobs +$50 at 25 to 40 miles. Zones as in tools/city_guides.py.
# Change them here when /pricing/ changes.
T_START = '<!-- trust:start (generated by tools/reviews_build.py from tools/reviews.json) -->'
T_END = '<!-- trust:end -->'
TRUST_RE = re.compile(r'[ \t]*<!-- trust:start.*?<!-- trust:end -->\n', re.S)
CTA_RE = re.compile(r'          <div class="cta-row">\n.*?\n          </div>\n', re.S)
KEY_FROM, FAR_ADD = 140, 50
GENERAL = ('Lockout from $75', 'Keys from $%d' % KEY_FROM)          # pages that cover more than one zone
ZONE = {1: ('Lockout $75', 'Keys from $%d' % KEY_FROM), 2: ('Lockout $100', 'Keys from $%d' % KEY_FROM),
        3: ('Lockout $125', 'Keys from $%d' % (KEY_FROM + FAR_ADD)), 4: None}   # 4: beyond 40 miles, quoted by Mitch, no numbers
TRUST_PAGES = {'index.html': GENERAL, 'car-key-replacement/index.html': GENERAL, 'all-keys-lost/index.html': GENERAL,
               'spare-key/index.html': GENERAL, 'car-lockout/index.html': GENERAL, 'key-programming/index.html': GENERAL,
               'lake-lanier/index.html': GENERAL, 'gwinnett-county/index.html': GENERAL,
               'forsyth-county/index.html': ZONE[1], 'north-fulton/index.html': ('Lockout from $100', 'Keys from $%d' % KEY_FROM)}
for _zone, _slugs in {1: 'cumming sugarhill', 2: 'alpharetta milton johnscreek buford suwanee duluth roswell dawsonville gainesville flowerybranch dunwoody lawrenceville canton',
                      3: 'peachtreecorners sandysprings norcross doraville braselton woodstock smyrna', 4: 'marietta kennesaw'}.items():
    for _slug in _slugs.split():
        TRUST_PAGES[_slug + '/index.html'] = ZONE[_zone]

DATA = json.load(open(os.path.join(ROOT, 'tools', 'reviews.json'), encoding='utf-8'))
REVIEWS = DATA['reviews']
COUNT = len(REVIEWS)
SHOW_COUNT_FROM = 10   # below this the number of reviews is not shown ("2 reviews" works against us): Dima, 2026-11-18
AVG = sum(r['rating'] for r in REVIEWS) / COUNT
PROFILE = DATA['profile_url']   # one button, to the profile; the write-a-review link is not used on the site (Dima, 2026-11-18)


def day(iso):
    return datetime.date.fromisoformat(iso)


def stars(n, label):
    n = int(round(n))
    return '<span class="rv-stars" role="img" aria-label="%s out of 5 stars">%s</span>' % (label, '★' * n + '☆' * (5 - n))


def block():
    cards = ''.join(
        '        <figure class="rv">\n'
        '          %s\n'
        '          <blockquote><p>%s</p></blockquote>\n'
        '          <figcaption><b>%s</b><span>%s review · %s</span></figcaption>\n'
        '        </figure>\n' % (stars(r['rating'], r['rating']), html.escape(r['text'], quote=False), html.escape(r['name'], quote=False),
                                 html.escape(r['source'], quote=False), day(r['date']).strftime('%B %Y'))
        for r in REVIEWS)
    return ('  ' + START + '\n'
            '  <section class="reviews-sec" id="reviews">\n'
            '    <div class="wrap">\n'
            '      <div class="sec-head">\n'
            '        <h2>What customers say</h2>\n'
            '        <p class="lede rv-sum"><b>%.1f</b>%s<span>%s</span></p>\n'
            '      </div>\n'
            '      <div class="rv-list">\n%s      </div>\n'
            '      <div class="rv-cta">\n'
            '        <a class="btn btn-ghost" href="%s" target="_blank" rel="noopener">See our reviews on Google</a>\n'
            '      </div>\n'
            '    </div>\n'
            '  </section>\n'
            '  ' + END + '\n\n') % (AVG, stars(AVG, '%.1f' % AVG), ('%d reviews on Google' % COUNT) if COUNT >= SHOW_COUNT_FROM else 'on Google', cards, PROFILE)


def trust_block(prices):
    # Rating on its own, larger row (five stars + "5.0 on Google"), prices on the row below: Dima, 2026-11-18 evening.
    # tools/es_build.py matches ' on Google</a>' and '>Lockout from $' / '>Keys from $': keep those substrings.
    rating = ('<a class="tl-g" href="%s" target="_blank" rel="noopener"><span class="tl-star" aria-hidden="true">%s</span><b>%.1f</b> on Google</a>'
              % (PROFILE, '★' * int(round(AVG)), AVG))
    if prices:
        rest = '<span aria-hidden="true">·</span>'.join('<a class="tl-p" href="/pricing/">%s</a>' % p for p in prices)
    else:
        rest = '<a class="tl-p" href="/pricing/">Price by text before we drive out</a>'
    return ('          ' + T_START + '\n'
            '          <p class="trust-line">' + rating + '<span class="tl-prices">' + rest + '</span></p>\n'
            '          ' + T_END + '\n')


def fix_trust(s, rel):
    s = TRUST_RE.sub('', s)
    if rel not in TRUST_PAGES:
        return s
    m = CTA_RE.search(s)
    if not m:
        raise SystemExit('no hero buttons to put the trust line under in ' + rel)
    return s[:m.end()] + trust_block(TRUST_PAGES[rel]) + s[m.end():]


def review_ld():
    value = int(AVG) if AVG == int(AVG) else round(AVG, 1)
    agg = {'@type': 'AggregateRating', 'ratingValue': value, 'reviewCount': COUNT, 'bestRating': 5}
    items = [{'@type': 'Review', 'author': {'@type': 'Person', 'name': r['name']},
              'reviewRating': {'@type': 'Rating', 'ratingValue': r['rating'], 'bestRating': 5},
              'reviewBody': r['text'], 'datePublished': r['date'],
              'publisher': {'@type': 'Organization', 'name': r['source']}} for r in REVIEWS]
    return agg, items


def locksmith(node):
    """The Locksmith object of a JSON-LD block: the block itself or the provider of a Service."""
    if isinstance(node, dict):
        if node.get('@type') == 'Locksmith':
            return node
        if isinstance(node.get('provider'), dict) and node['provider'].get('@type') == 'Locksmith':
            return node['provider']
    return None


def fix_ld(s, shown):
    def one(m):
        node = json.loads(m.group(1))
        biz = locksmith(node)
        if biz is None:
            return m.group(0)
        biz.pop('aggregateRating', None)
        biz.pop('review', None)
        if shown and REVIEW_MARKUP:
            biz['aggregateRating'], biz['review'] = review_ld()
        if 'sameAs' in biz and PROFILE not in biz['sameAs']:
            biz['sameAs'].insert(0, PROFILE)
        return '<script type="application/ld+json">' + json.dumps(node, ensure_ascii=False) + '</script>'
    return re.sub(r'<script type="application/ld\+json">(.*?)</script>', one, s, flags=re.S)


def fix_page(rel):
    path = os.path.join(ROOT, rel)
    old = open(path, encoding='utf-8').read()
    shown = rel in PAGES
    s = BLOCK_RE.sub('', old)
    if shown:
        m = AFTER_RE.search(s)
        if not m:
            raise SystemExit('no "Recent jobs" section to put the reviews after in ' + rel)
        s = s[:m.end()] + block() + s[m.end():]
    s = fix_ld(s, shown)
    s = fix_trust(s, rel)
    if s != old:
        open(path, 'w', encoding='utf-8').write(s)
    return s != old


def fix_llms():
    path = os.path.join(ROOT, 'llms.txt')
    old = open(path, encoding='utf-8').read()
    d = day(DATA['checked'])
    lines = ['- Google Business Profile: ' + PROFILE,
             '- Google reviews: %.1f out of 5%s, as of %s %d, %d. Read them: %s' % (
                 AVG, (' from %d reviews' % COUNT) if COUNT >= SHOW_COUNT_FROM else '', d.strftime('%b'), d.day, d.year, PROFILE)]
    s = re.sub(r'- Google Business Profile: [^\n]*\n|- Google reviews: [^\n]*\n|- Google: [^\n]*\n', '', old)
    head, sep, tail = s.partition('## Profiles\n')
    if not sep or '- Yelp: ' not in head or '- Yelp: ' not in tail:
        raise SystemExit('llms.txt: Yelp lines not found')
    head = head.replace('- Yelp: ', '\n'.join(lines) + '\n- Yelp: ', 1)
    tail = '- Google: ' + PROFILE + '\n' + tail
    s = head + sep + tail
    if s != old:
        open(path, 'w', encoding='utf-8').write(s)
    return s != old


def main():
    pages = sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, '**', '*.html'), recursive=True))
    changed = [p for p in pages if not p.startswith('es' + os.sep) and fix_page(p)]
    llms = fix_llms()
    print('reviews: %d, average %.1f; pages changed: %d%s' % (COUNT, AVG, len(changed), ', llms.txt changed' if llms else ''))


main()
